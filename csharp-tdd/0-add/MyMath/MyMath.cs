namespace MyMath
{
    /// <summary>
    /// Contains basic math operations.
    /// </summary>
    public class Operations
    {
        /// <summary>
        /// Adds two integers.
        /// </summary>
        /// <param name="a">First number.</param>
        /// <param name="b">Second number.</param>
        /// <returns>The sum of a and b.</returns>
        public static int Add(int a, int b)
        {
            return a + b;
        }
    }
}